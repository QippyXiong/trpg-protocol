#!/usr/bin/env node
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {dirname,resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
const root=fileURLToPath(new URL('../',import.meta.url));
const args=process.argv.slice(2),kind=args[0],check=args.includes('--check');
if(!['server','web','cli'].includes(kind)){console.error('Usage: trpg-protocol-sync server|web|cli [--check]');process.exit(2)}
const raw=await readFile(resolve(root,'contract.json'),'utf8'),contract=JSON.parse(raw);
const targets={server:'protocol.json',web:'static/protocol.js',cli:'nighttable_cli/protocol.json'};
const content=kind==='web'?'// Generated by trpg-protocol; do not edit.\nglobalThis.TRPGProtocol=Object.freeze('+JSON.stringify(contract)+');\n':raw;
const output=resolve(process.cwd(),targets[kind]);
const lock=JSON.stringify({package:'trpg-protocol',version:contract.version,sha256:createHash('sha256').update(raw).digest('hex')},null,2)+'\n';
for(const [file,data] of [[output,content],[resolve(process.cwd(),'protocol.lock.json'),lock]]){
 if(check){let current;try{current=await readFile(file,'utf8')}catch{}if(current!==data){console.error('Out of sync: '+file);process.exitCode=1}}
 else{await mkdir(dirname(file),{recursive:true});await writeFile(file,data)}
}
if(!process.exitCode)console.log((check?'Verified':'Synced')+' protocol '+contract.version+' for '+kind);
